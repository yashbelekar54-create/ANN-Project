"""Category explorer."""
import json

import joblib
import pandas as pd
import streamlit as st

from components.ui import config, read_json, results_path, setup_page
from src.categories import describe
from src.config import resolve
from src.data_loader import load_processed_dataset

setup_page("Category Explorer", "The 20 categories of the 20 Newsgroups corpus and how the model sees them.")
cfg = config()

le_path = resolve(cfg, "label_encoder_file")
if le_path.exists():
    names = list(joblib.load(le_path).classes_)
else:
    mapping = read_json("category_mapping_file")
    names = list(mapping.values()) if mapping else sorted([
        "alt.atheism", "comp.graphics", "comp.os.ms-windows.misc", "comp.sys.ibm.pc.hardware", "comp.sys.mac.hardware",
        "comp.windows.x", "misc.forsale", "rec.autos", "rec.motorcycles", "rec.sport.baseball", "rec.sport.hockey",
        "sci.crypt", "sci.electronics", "sci.med", "sci.space", "soc.religion.christian", "talk.politics.guns",
        "talk.politics.mideast", "talk.politics.misc", "talk.religion.misc"])
    st.info("Category names shown from the standard 20 Newsgroups list; the trained label encoder is not available yet.")

summary = read_json("dataset_summary_file")
terms_path = results_path("metrics", "top_terms_per_category.json")
top_terms = json.loads(terms_path.read_text(encoding="utf-8")) if terms_path.exists() else {}

st.subheader("Category distribution")
if summary:
    counts = pd.Series(summary["category_counts_total"]).reindex(names)
    st.bar_chart(counts, color="#3949ab")
    st.caption(f"Class imbalance (largest / smallest class): {summary['imbalance_ratio_max_to_min_class']:.2f}")
else:
    st.info("Category counts will appear after the dataset is prepared (`python -m src.data_loader`).")

st.subheader("Categories")
choice = st.selectbox("Select a category", names)
st.markdown(f"**{choice}** - {describe(choice)}")
if choice in top_terms:
    st.write("Most characteristic TF-IDF terms (training set): " + ", ".join(f"`{t}`" for t in top_terms[choice]))
else:
    st.caption("Characteristic terms are generated by `python -m src.evaluate`.")

if resolve(cfg, "processed_csv").exists():
    try:
        df = load_processed_dataset(cfg)
        sample = df[(df["category"] == choice) & (df["dataset_split"] == "train") & (df["cleaned_text"].str.len() > 200)].head(1)
        if len(sample):
            with st.expander("Example training document (cleaned text, first 600 characters)"):
                st.text(sample.iloc[0]["cleaned_text"][:600] + "...")
    except Exception as exc:
        st.caption(f"Example unavailable: {exc}")

st.subheader("All categories")
table = pd.DataFrame({"Category": names, "Description": [describe(n) for n in names]})
if summary:
    table["Documents"] = [summary["category_counts_total"].get(n, 0) for n in names]
st.dataframe(table, hide_index=True, use_container_width=True)
